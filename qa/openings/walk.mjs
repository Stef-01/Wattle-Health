// Walks Me › Openings (two saved doctors, demo week) and Discover › Healthspan; screenshots each.
import { chromium } from "@playwright/test";
const BASE = (process.env.BASE ?? "http://localhost:3300").replace(/\/$/, "");
const OUT = "qa/openings";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 2 });
await ctx.grantPermissions(["notifications"], { origin: BASE });
const page = await ctx.newPage();
await page.goto(`${BASE}/`);
await page.evaluate(() => { localStorage.setItem("wattle.splash.seen", "true"); localStorage.setItem("wattle.saved.v1", JSON.stringify(["general-practice:sian-hebron", "obstetrics-gynaecology:tal-jacobson"])); });
await page.goto(`${BASE}/me/openings`);
await page.waitForSelector("text=/fit your next two weeks|Nothing fits yet/", { timeout: 20000 });
await page.waitForTimeout(800);
const heading = await page.locator("h2").first().innerText();
const cards = await page.locator("article").count();
await page.screenshot({ path: `${OUT}/01-openings.png`, fullPage: true });
await page.getByRole("button", { name: "Afternoons, 2 to 5" }).click();
await page.waitForTimeout(600);
const afterToggle = await page.locator("h2").first().innerText();
await page.goto(`${BASE}/`);
await page.waitForSelector("a[href='/me/openings']", { timeout: 15000 }).catch(() => null);
const banner = await page.locator("a[href='/me/openings']").count();
await page.screenshot({ path: `${OUT}/02-home-banner.png` });
const area = "covered by qa/iphone/healthspan.mjs";
console.log(JSON.stringify({ heading, cards, afterToggle, banner, area }));
await b.close();
