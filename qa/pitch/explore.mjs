import { chromium, devices } from "@playwright/test";
import { throughNarrow } from "../figma/narrow-helper.mjs";
const BASE = process.env.BASE ?? "https://wattlehealth.vercel.app";
const b = await chromium.launch();
const page = await (await b.newContext({ ...devices["iPhone 15"] })).newPage();
await page.goto(`${BASE}/`);
await page.evaluate(() => { localStorage.setItem("wattle.splash.seen", "true"); localStorage.setItem("wattle.brand.v1", "adhdme"); });
await page.goto(`${BASE}/`);
console.log("TITLE", await page.title());
await page.locator("textarea, input[type=text]").first().fill("ADHD. I keep forgetting to book.");
await page.getByText("Find my provider").click();
await throughNarrow(page).catch((e) => console.log("narrow", e.message));
await page.waitForSelector("text=Your top pick", { timeout: 30000 });
const links = await page.locator("a[href*='/doctor']").evaluateAll((els) => els.slice(0, 4).map((e) => e.getAttribute("href") + " | " + e.innerText.slice(0, 60).replace(/\n/g, " ")));
console.log(links.join("\n"));
await page.locator("a[href*='/doctor']").first().click();
await page.waitForTimeout(2500);
console.log("URL", page.url());
const btns = await page.locator("button, [role=tab], [role=radio]").evaluateAll((els) => els.map((e) => (e.getAttribute("role") || e.tagName) + ":" + e.innerText.trim().slice(0, 40)).filter((s) => s.length > 6));
console.log(btns.join("\n"));
await b.close();
